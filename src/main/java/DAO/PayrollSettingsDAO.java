package DAO;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.LocalDateTime;

import model.DBcConnection;

/**
 * Automatic payroll schedule (one row, table payroll_settings - created
 * automatically): switch, pay day of the month and run time.
 */
public class PayrollSettingsDAO {

    public static class Settings {
        public boolean enabled = true;
        public int payDay = 1;          // 1 - 31 (beyond the month's length = last day)
        public int runHour = 9;         // 0 - 23
        public String lastRunMonth;     // yyyy-MM of the month already generated by the schedule
        public LocalDateTime lastRunAt;
        public String lastRunNote;
    }

    private void ensureTable(Connection con) throws SQLException {
        try (Statement st = con.createStatement()) {
            st.executeUpdate(
                "CREATE TABLE IF NOT EXISTS payroll_settings (" +
                "id INT NOT NULL PRIMARY KEY, " +
                "auto_enabled TINYINT(1) NOT NULL DEFAULT 1, " +
                "pay_day INT NOT NULL DEFAULT 1, " +
                "run_hour INT NOT NULL DEFAULT 9, " +
                "last_run_month VARCHAR(7) NULL, " +
                "last_run_at DATETIME NULL, " +
                "last_run_note VARCHAR(500) NULL)");
            st.executeUpdate("INSERT IGNORE INTO payroll_settings (id) VALUES (1)");
        }
    }

    public Settings get() throws SQLException {

        try (Connection con = DBcConnection.getConnection()) {
            ensureTable(con);

            try (PreparedStatement ps = con.prepareStatement(
                    "SELECT auto_enabled, pay_day, run_hour, last_run_month, " +
                    "last_run_at, last_run_note FROM payroll_settings WHERE id = 1");
                 ResultSet rs = ps.executeQuery()) {

                Settings s = new Settings();

                if (rs.next()) {
                    s.enabled = rs.getBoolean(1);
                    s.payDay = rs.getInt(2);
                    s.runHour = rs.getInt(3);
                    s.lastRunMonth = rs.getString(4);
                    Timestamp t = rs.getTimestamp(5);
                    if (t != null) s.lastRunAt = t.toLocalDateTime();
                    s.lastRunNote = rs.getString(6);
                }

                return s;
            }
        }
    }

    public void save(boolean enabled, int payDay, int runHour) throws SQLException {

        if (payDay < 1 || payDay > 31) {
            throw new IllegalArgumentException("Pay day must be between 1 and 31.");
        }
        if (runHour < 0 || runHour > 23) {
            throw new IllegalArgumentException("Run time must be between 00:00 and 23:00.");
        }

        try (Connection con = DBcConnection.getConnection()) {
            ensureTable(con);

            try (PreparedStatement ps = con.prepareStatement(
                    "UPDATE payroll_settings SET auto_enabled = ?, pay_day = ?, run_hour = ? WHERE id = 1")) {
                ps.setBoolean(1, enabled);
                ps.setInt(2, payDay);
                ps.setInt(3, runHour);
                ps.executeUpdate();
            }
        }
    }

    public void markRun(String month, String note) throws SQLException {

        try (Connection con = DBcConnection.getConnection()) {
            ensureTable(con);

            try (PreparedStatement ps = con.prepareStatement(
                    "UPDATE payroll_settings SET last_run_month = ?, last_run_at = NOW(), " +
                    "last_run_note = ? WHERE id = 1")) {
                ps.setString(1, month);
                ps.setString(2, note == null ? null : (note.length() > 480 ? note.substring(0, 480) : note));
                ps.executeUpdate();
            }
        }
    }
}
